"""Write scripts/voice/lines.json and scripts/voice/render-voice-mac.sh from content/films/*.json (voiced films).

  python3 scripts/voice/make-job.py

Each caption line may carry speak_zh / speak_en: the text the voice reads when the caption contains symbols
(×, →, coordinates) that a speech engine would read badly. The caption itself is unchanged.
"""
import json
import shlex
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
items = []
for film in sorted((ROOT / "content" / "films").glob("*.json")):
    d = json.loads(film.read_text(encoding="utf-8"))
    if d.get("kind") != "voice":
        continue
    for c in d["cues"]:
        for i, line in enumerate(c["lines"]):
            for lang in ("zh", "en"):
                items.append({"key": f"{d['id']}-{c['id']}-{i + 1}-{lang}", "lang": lang, "text": line.get(f"speak_{lang}") or line[lang]})
(ROOT / "scripts/voice/lines.json").write_text(json.dumps(items, ensure_ascii=False, indent=1), encoding="utf-8")
sh = [
    "#!/bin/zsh",
    "# Render voiceover lines with macOS built-in voices (run on a Mac).",
    "# Writes media-source/voice/<film>-<cue>-<line>-<lang>.m4a (AAC 128k) plus voices.json and the voice list.",
    "# Durations are measured later by scripts/build-clock.mjs. Generated by scripts/voice/make-job.py.",
    "set -eu",
    'cd "$(dirname "$0")/../.."',
    "OUT=media-source/voice",
    'mkdir -p "$OUT"',
    'pick() { say -v "?" | grep -E " $1( |$)" | grep -E "\\((Premium|Enhanced)\\)" | head -1 | sed -E "s/ +$1.*//" ; }',
    'ZH="${HPWL_VOICE_ZH:-$(pick zh_CN)}"; [ -n "$ZH" ] || ZH=Tingting',
    'EN="${HPWL_VOICE_EN:-$(pick en_US)}"; [ -n "$EN" ] || EN=Samantha',
    'echo "zh voice: $ZH"; echo "en voice: $EN"',
    'say -v "?" > "$OUT/voices-available.txt"',
    'sw_vers > "$OUT/system.txt"',
    'v() { say -v "$1" -o "$OUT/$2.aiff" "$3" && afconvert -f m4af -d aac@44100 -b 128000 "$OUT/$2.aiff" "$OUT/$2.m4a" && rm "$OUT/$2.aiff"; }',
]
for it in items:
    voice = '"$ZH"' if it["lang"] == "zh" else '"$EN"'
    sh.append(f"v {voice} {it['key']} {shlex.quote(it['text'])}")
sh.append('printf \'{"zh": "%s", "en": "%s"}\\n\' "$ZH" "$EN" > "$OUT/voices.json"')
sh.append('echo "$(ls "$OUT"/*.m4a | wc -l) files"; echo done')
(ROOT / "scripts/voice/render-voice-mac.sh").write_text("\n".join(sh) + "\n", encoding="utf-8")
print(len(items), "lines")
